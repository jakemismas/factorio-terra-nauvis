-- Space Age compatibility probe (test only; tools/sa_compat.py reads its output): what every planet
-- generates in fixed chunk blocks, so a run with the mod under test and its twin without it compare
-- tile for tile, entity for entity and decorative for decorative (D33 and T14 on the real planets).
--
-- Tick 3: every planet but Nauvis gets its surface through LuaPlanet.create_surface, which raises
-- on_surface_created inside the call (S11) as the engine's own creation does when a platform first
-- reaches a planet; then each planet surface and Nauvis generate the near block (chunks -4..4 around
-- the origin) and the far block, forced once per surface, and each surface's digest is written.
-- Tick 4: when the expansion is active, a space platform is built; its surface raises
-- on_surface_created too, and its property_expression_names are recorded.
--
-- No dependency, so this probe loads before terra-nauvis: its on_surface_created handler runs first
-- and records what a new surface inherited from the save's defaults before any guard ran; the digest
-- reads the same table again after create_surface returned, so after every guard.
--
-- Travel mode (the marker mod ea-sa-travel is active): no create_surface. A space platform is built at
-- Nauvis at tick 3 and moved into each other planet's orbit in turn (LuaSpacePlatform.space_location),
-- every 10 ticks, so any planet surface comes from the engine's own creation; at the end the probe
-- records which chunks the engine generated by itself and writes the same digests as travel-surface-*.
--
-- Options (settings.lua, runtime-global, read in on_init): ea-sa-probe-blocks picks the block set (standard: the
-- near block, chunks -4..4, and the far block, 90 chunks per surface; wide: 491 chunks per surface, the near block
-- -10..10 and two far blocks); ea-sa-probe-landing, in travel mode, sends a cargo pod from the platform's hub down to
-- each planet two ticks after the platform reaches it (destination: that planet's surface at LAND, exactly), finishes
-- its ascent at once and its descent three ticks later, and adds the landing block to the digests. Before the first
-- move it also tries a pod towards the first planet, whose surface does not exist yet, and records what happened:
-- whether a cargo pod can create a planet surface at all.
local DIR = "ea-sa-probe/"
local START = 3
local TRAVEL = script.active_mods["ea-sa-travel"] ~= nil
local MOVE = 10
local BLOCKS = {
  {name = "near", cx = 0, cy = 0, r = 4},
  {name = "far", cx = 64, cy = -24, r = 1},
}
local BLOCK_SETS = {
  standard = BLOCKS,
  wide = {
    {name = "near", cx = 0, cy = 0, r = 10},
    {name = "far", cx = 64, cy = -24, r = 2},
    {name = "far2", cx = -90, cy = 50, r = 2},
  },
}
local LAND = {x = 480, y = -352}

-- The block set this save digests (storage, from the option at on_init), with the landing block in travel mode.
local function blocks()
  return storage.blocks or BLOCKS
end
local PROPS = {"elevation", "distance", "starting_resources_lake_mask"}
local SAMPLES = {{0, 0}, {37, -91}, {150, 150}, {-300, 210}, {600, -40}, {2053, -759}}

local M32 = 4294967296

-- Every intermediate stays below 2^53, so the double arithmetic is exact and the digest is stable.
local function mix(h, v)
  return (h * 65599 + v) % M32
end

local ids = {}
local function sid(s)
  local id = ids[s]
  if not id then
    id = 5381
    for i = 1, #s do
      id = (id * 33 + string.byte(s, i)) % M32
    end
    ids[s] = id
  end
  return id
end

-- A map coordinate in 1/256 tile as a non-negative 32-bit number.
local function q(v)
  return math.floor(v * 256 + 0.5) % M32
end

-- helpers.table_to_json writes non-finite numbers bare, which no JSON reader accepts.
local function finite(v)
  if v ~= v then
    return "nan"
  elseif v == math.huge then
    return "inf"
  elseif v == -math.huge then
    return "-inf"
  end
  return v
end

local function pen_copy(surface)
  local ok, res = pcall(function()
    local out = {}
    for k, v in pairs(surface.map_gen_settings.property_expression_names or {}) do
      out[k] = tostring(v)
    end
    return out
  end)
  if ok then
    return res
  end
  return {["ea-sa-probe-error"] = tostring(res)}
end

local function add(t, k, n)
  t[k] = (t[k] or 0) + (n or 1)
end

local function write(name, t)
  helpers.write_file(DIR .. name .. ".json", helpers.table_to_json(t), false)
end

local function digest_chunk(s, cx, cy, totals)
  local x0, y0 = cx * 32, cy * 32
  local th = 0
  for y = y0, y0 + 31 do
    for x = x0, x0 + 31 do
      local n = s.get_tile(x, y).name
      th = mix(th, sid(n))
      add(totals.tiles, n)
    end
  end
  local area = {{x0, y0}, {x0 + 32, y0 + 32}}
  -- Entity and decorative digests are sums, so the order a find returns does not matter; an item is
  -- counted in the chunk holding its position only.
  local eh, en = 0, 0
  for _, e in pairs(s.find_entities_filtered{area = area}) do
    local p = e.position
    if p.x >= x0 and p.x < x0 + 32 and p.y >= y0 and p.y < y0 + 32 then
      local amount = 0
      if e.type == "resource" then
        amount = e.amount
        add(totals.resource_amount, e.name, amount)
      end
      local v = mix(mix(mix(mix(mix(0, sid(e.name)), q(p.x)), q(p.y)), e.direction or 0), amount % M32)
      eh = (eh + v) % M32
      en = en + 1
      add(totals.entities, e.name)
    end
  end
  local dh, dn = 0, 0
  for _, d in pairs(s.find_decoratives_filtered{area = area}) do
    local p = d.position
    if p.x >= x0 and p.x < x0 + 32 and p.y >= y0 and p.y < y0 + 32 then
      local name = d.decorative.name
      local v = mix(mix(mix(mix(0, sid(name)), q(p.x)), q(p.y)), d.amount)
      dh = (dh + v) % M32
      dn = dn + 1
      add(totals.decoratives, name)
    end
  end
  return {t = th, e = eh, en = en, d = dh, dn = dn}
end

local function surface_report(s)
  local created = (storage.created or {})[s.name]
  local r = {surface = s.name, index = s.index, planet = s.planet and s.planet.name or nil,
             seed = s.map_gen_settings.seed, created_tick = created and created.tick or nil,
             pen_before_guard = created and created.pen or nil, pen = pen_copy(s), blocks = {}, props = {}}
  for _, b in ipairs(blocks()) do
    local totals = {tiles = {}, entities = {}, decoratives = {}, resource_amount = {}}
    local chunks, missing = {}, 0
    for cy = b.cy - b.r, b.cy + b.r do
      for cx = b.cx - b.r, b.cx + b.r do
        if s.is_chunk_generated({x = cx, y = cy}) then
          chunks[cx .. "," .. cy] = digest_chunk(s, cx, cy, totals)
        else
          missing = missing + 1
        end
      end
    end
    r.blocks[b.name] = {chunks = chunks, missing = missing, totals = totals}
  end
  -- The player force's spawn on this surface and every tile within 12 tiles of it, with the number a
  -- character cannot walk on.
  local spawn = game.forces.player.get_spawn_position(s)
  local sx, sy = math.floor(spawn.x), math.floor(spawn.y)
  local blocking, near = 0, {}
  for y = sy - 12, sy + 12 do
    for x = sx - 12, sx + 12 do
      if (x - sx) * (x - sx) + (y - sy) * (y - sy) <= 144 then
        local t = s.get_tile(x, y)
        add(near, t.name)
        if t.collides_with("player") then
          blocking = blocking + 1
        end
      end
    end
  end
  r.spawn = {x = spawn.x, y = spawn.y, tile = s.get_tile(sx, sy).name, blocking_within_12 = blocking,
             tiles_within_12 = near}
  local positions = {}
  for _, p in ipairs(SAMPLES) do
    positions[#positions + 1] = {x = p[1], y = p[2]}
  end
  local props = s.calculate_tile_properties(PROPS, positions)
  for name, values in pairs(props) do
    local list = {}
    for i, v in ipairs(values) do
      list[i] = finite(v)
    end
    r.props[name] = list
  end
  return r
end

local function planets_stage()
  local summary = {tick = game.tick, active_mods = script.active_mods, default_pen = {}, planets = {},
                   surfaces = {}}
  for k, v in pairs(game.default_map_gen_settings.property_expression_names or {}) do
    summary.default_pen[k] = tostring(v)
  end
  local names = {}
  for name in pairs(game.planets) do
    names[#names + 1] = name
  end
  table.sort(names)
  local order = {"nauvis"}
  for _, name in ipairs(names) do
    summary.planets[#summary.planets + 1] = name
    if name ~= "nauvis" then
      local planet = game.planets[name]
      log("ea-sa-probe: creating the surface of planet " .. name)
      local s = planet.surface or planet.create_surface()
      order[#order + 1] = s.name
    end
  end
  for _, sname in ipairs(order) do
    local s = game.surfaces[sname]
    log("ea-sa-probe: generating surface " .. sname)
    for _, b in ipairs(blocks()) do
      s.request_to_generate_chunks({x = b.cx * 32 + 16, y = b.cy * 32 + 16}, b.r)
    end
    s.force_generate_chunk_requests()
    write("surface-" .. sname, surface_report(s))
    summary.surfaces[#summary.surfaces + 1] = sname
    log("ea-sa-probe: wrote " .. DIR .. "surface-" .. sname .. ".json")
  end
  write("summary", summary)
end

local function platform_stage()
  local res = {tick = game.tick}
  if not prototypes.item["space-platform-starter-pack"] then
    res.skipped = "no space-platform-starter-pack item"
  else
    local ok, err = pcall(function()
      local p = game.forces.player.create_space_platform{name = "ea-sa-probe-platform", planet = "nauvis",
                                                          starter_pack = "space-platform-starter-pack"}
      res.created = p ~= nil
      if p then
        res.hub = p.apply_starter_pack() ~= nil
        local s = p.surface
        if s and s.valid then
          res.surface = s.name
          res.pen = pen_copy(s)
          local created = (storage.created or {})[s.name]
          res.pen_before_guard = created and created.pen or nil
        end
      end
    end)
    res.ok = ok
    if not ok then
      res.error = tostring(err)
    end
  end
  log("ea-sa-probe: platform stage " .. helpers.table_to_json(res))
  write("platform", res)
end

local function generated_chunks(s)
  local out = {}
  for c in s.get_chunks() do
    if s.is_chunk_generated({x = c.x, y = c.y}) then
      out[#out + 1] = c.x .. "," .. c.y
    end
  end
  table.sort(out)
  return out
end

-- Cargo pods (ea-sa-probe-landing): one towards the first planet before any surface of it exists, then one down to
-- each planet two ticks after the platform reaches it, its descent finished three ticks later.
local function land_step(t, tick)
  if not storage.landing then
    return
  end
  t.landings = t.landings or {}
  local p = t.platform
  local first = (t.order or {})[1]
  if tick == START + 1 and p and p.valid and first then
    local rec = {tick = tick, planet = first, surface_before = game.planets[first].surface ~= nil}
    local ok, err = pcall(function()
      local pod = p.hub and p.hub.create_cargo_pod()
      rec.created = pod ~= nil
      if pod then
        pod.cargo_pod_destination = {type = defines.cargo_destination.surface, surface = first, position = LAND,
                                     land_at_exact_position = true}
        rec.destination_set = true
        rec.surface_after = game.planets[first].surface ~= nil
        if pod.valid then
          pod.destroy()
        end
      end
    end)
    rec.ok, rec.error = ok, (not ok) and tostring(err) or nil
    rec.surface_after = game.planets[first].surface ~= nil
    t.pre_arrival = rec
    log("ea-sa-probe: cargo pod before arrival " .. helpers.table_to_json(rec))
  end
  for i, name in ipairs(t.order or {}) do
    local m = START + 2 + (i - 1) * MOVE
    if tick == m + 2 and p and p.valid then
      local rec = {tick = tick, surface_before = game.planets[name].surface ~= nil}
      local ok, err = pcall(function()
        local pod = p.hub and p.hub.create_cargo_pod()
        rec.created = pod ~= nil
        if pod then
          local s = game.planets[name].surface
          pod.cargo_pod_destination = {type = defines.cargo_destination.surface, surface = s or name, position = LAND,
                                       land_at_exact_position = true}
          pod.force_finish_ascending()
          t.pods = t.pods or {}
          t.pods[name] = pod
          rec.ascended = true
          rec.pod_surface = pod.valid and pod.surface.name or nil
        end
      end)
      rec.ok, rec.error = ok, (not ok) and tostring(err) or nil
      t.landings[name] = rec
    elseif tick == m + 5 then
      local rec = t.landings[name]
      local pod = t.pods and t.pods[name]
      if rec and pod and pod.valid then
        local ok, err = pcall(function()
          pod.force_finish_descending()
        end)
        rec.descended, rec.descend_error = ok, (not ok) and tostring(err) or nil
      end
      if rec then
        local s = game.planets[name].surface
        rec.landing_chunk_generated = s ~= nil and s.is_chunk_generated({x = math.floor(LAND.x / 32),
                                                                         y = math.floor(LAND.y / 32)})
        log("ea-sa-probe: cargo pod landing on " .. name .. " " .. helpers.table_to_json(rec))
      end
    end
  end
end

local function travel_tick(tick)
  local t = storage.travel
  if t.done then
    return
  end
  land_step(t, tick)
  if tick == START then
    local names = {}
    for name in pairs(game.planets) do
      if name ~= "nauvis" then
        names[#names + 1] = name
      end
    end
    table.sort(names)
    t.order = names
    local ok, err = pcall(function()
      local p = game.forces.player.create_space_platform{name = "ea-sa-probe-travel", planet = "nauvis",
                                                          starter_pack = "space-platform-starter-pack"}
      t.platform_created = p ~= nil
      if p then
        t.hub = p.apply_starter_pack() ~= nil
        t.platform = p
      end
    end)
    t.platform_ok = ok
    if not ok then
      t.platform_error = tostring(err)
    end
    return
  end
  local p = t.platform
  for i, name in ipairs(t.order or {}) do
    if tick == START + 2 + (i - 1) * MOVE and p and p.valid then
      storage.in_move = name
      local ok, err = pcall(function()
        p.space_location = name
      end)
      storage.in_move = nil
      t.moves[name] = {tick = tick, ok = ok, error = (not ok) and tostring(err) or nil,
                       surface_right_after = game.planets[name].surface ~= nil, state = p.state,
                       location = p.space_location and p.space_location.name or nil}
      log("ea-sa-probe: platform moved to " .. name .. " " .. helpers.table_to_json(t.moves[name]))
    end
  end
  for _, name in ipairs(t.order or {}) do
    local s = game.planets[name].surface
    if s and not t.seen[name] then
      t.seen[name] = {tick = tick, generated_chunks = #generated_chunks(s)}
    end
  end
  if tick == START + 2 + #(t.order or {}) * MOVE + 10 then
    for _, name in ipairs(t.order or {}) do
      local s = game.planets[name].surface
      if s then
        t.engine_chunks[name] = generated_chunks(s)
        log("ea-sa-probe: generating surface " .. s.name)
        for _, b in ipairs(blocks()) do
          s.request_to_generate_chunks({x = b.cx * 32 + 16, y = b.cy * 32 + 16}, b.r)
        end
        s.force_generate_chunk_requests()
        write("travel-surface-" .. s.name, surface_report(s))
      end
    end
    t.done = true
    t.platform = nil
    t.pods = nil
    write("travel", t)
  end
end

script.on_init(function()
  storage.created = {}
  storage.stage = 0
  storage.travel = {moves = {}, seen = {}, engine_chunks = {}, landings = {}}
  local set = {}
  for _, b in ipairs(BLOCK_SETS[settings.global["ea-sa-probe-blocks"].value] or BLOCKS) do
    set[#set + 1] = b
  end
  storage.landing = TRAVEL and settings.global["ea-sa-probe-landing"].value or false
  if storage.landing then
    set[#set + 1] = {name = "landing", cx = math.floor(LAND.x / 32), cy = math.floor(LAND.y / 32), r = 1}
  end
  storage.blocks = set
end)

script.on_event(defines.events.on_surface_created, function(event)
  local s = game.get_surface(event.surface_index)
  if s then
    storage.created = storage.created or {}
    storage.created[s.name] = {tick = event.tick, pen = pen_copy(s), during_move = storage.in_move,
                               generated_chunks = #generated_chunks(s)}
    log("ea-sa-probe: on_surface_created " .. s.name)
  end
end)

script.on_event(defines.events.on_tick, function(event)
  if event.tick < START then
    return
  end
  if TRAVEL then
    travel_tick(event.tick)
    return
  end
  if (storage.stage or 0) >= 2 then
    return
  end
  if (storage.stage or 0) == 0 then
    storage.stage = 1
    planets_stage()
  else
    storage.stage = 2
    platform_stage()
  end
end)
